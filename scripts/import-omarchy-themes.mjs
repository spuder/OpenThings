// Regenerates src/lib/omarchy-themes.ts from an Omarchy checkout (MIT, © David Heinemeier Hansson).
//   git clone --depth 1 -b quattro https://github.com/omacom/omarchy /tmp/omarchy
//   node scripts/import-omarchy-themes.mjs /tmp/omarchy
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';

const root = process.argv[2];
if (!root) throw new Error('usage: node scripts/import-omarchy-themes.mjs <omarchy checkout>');
const dir = path.join(root, 'themes');
let commit = '';
try {
  commit = execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim();
} catch {
  /* not a git checkout */
}

const keys = ['accent', 'selection', 'muted', 'background', 'dark_background', 'darker_background', 'lighter_background', 'foreground', 'dark_foreground', 'light_foreground', 'bright_foreground', 'red', 'yellow', 'orange', 'green', 'cyan', 'blue', 'magenta', 'brown'];
const themes = [];
for (const name of fs.readdirSync(dir).sort()) {
  const file = path.join(dir, name, 'colors.toml');
  if (!fs.existsSync(file)) continue;
  const t = { id: name };
  for (const line of fs.readFileSync(file, 'utf8').split('\n')) {
    const m = /^\s*([a-z_]+)\s*=\s*"([^"]+)"/.exec(line);
    if (m) t[m[1]] = m[2];
  }
  if (!t.background || !t.foreground) continue;
  const out = { id: name, name: name.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' '), mode: t.mode === 'light' ? 'light' : 'dark' };
  for (const k of keys) out[k] = t[k] ?? (k.includes('background') ? t.background : k.includes('foreground') ? t.foreground : t.accent ?? t.blue);
  themes.push(out);
}

const ts = `// Generated by scripts/import-omarchy-themes.mjs — do not edit by hand.
// Palettes from Omarchy (https://github.com/omacom/omarchy, branch quattro${commit ? `, ${commit}` : ''}).
// Omarchy is MIT licensed, © David Heinemeier Hansson. See THIRD_PARTY_NOTICES.md.

export interface OmarchyPalette {
  id: string;
  name: string;
  mode: 'light' | 'dark';
${keys.map((k) => `  ${k}: string;`).join('\n')}
}

export const omarchyThemes: OmarchyPalette[] = ${JSON.stringify(themes, null, 2)};
`;
fs.writeFileSync(new URL('../src/lib/omarchy-themes.ts', import.meta.url), ts);
console.log(`wrote ${themes.length} themes`);
